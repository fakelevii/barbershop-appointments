require('dotenv').config({quiet:true});
const test=require('node:test');
const assert=require('node:assert/strict');
const mongoose=require('mongoose');
const {createApp}=require('../app');
const User=require('../models/User');
const Barber=require('../models/Barber');
const Service=require('../models/Service');
const Schedule=require('../models/Schedule');
const Appointment=require('../models/Appointment');
const {issueToken}=require('../auth/security');
test('real MongoDB booking, concurrency, access and schedule flow',async(t)=>{
 const dbName='barbershop_test_'+Date.now()+process.pid;
 assert.match(dbName,/^barbershop_test_\d+$/);
 await mongoose.connect(process.env.MONGODB_URI,{dbName,serverSelectionTimeoutMS:5000});
 t.after(async()=>{ if(mongoose.connection.name!==dbName || !/^barbershop_test_\d+$/.test(dbName)) throw new Error('Test cleanup target mismatch'); await mongoose.connection.dropDatabase();await mongoose.disconnect(); });
 await Promise.all([User,Barber,Service,Schedule,Appointment].map(m=>m.init()));
 const secret='a'.repeat(48);
 const server=createApp({jwtSecret:secret}).listen(0,'127.0.0.1');
 await new Promise(r=>server.once('listening',r));
 t.after(()=>new Promise(r=>server.close(r)));
 const base='http://127.0.0.1:'+server.address().port;
 const call=async(path,method='GET',body,cookie)=>{
  const response=await fetch(base+'/api'+path,{method,headers:{'Content-Type':'application/json',Origin:'http://127.0.0.1:5173',...(cookie?{Cookie:cookie}:{})},...(body?{body:JSON.stringify(body)}:{})});
  return {status:response.status,data:await response.json(),cookie:response.headers.get('set-cookie')?.split(';')[0]};
 };
 const first=await call('/auth/register','POST',{name:'Customer One',email:'one@example.com',password:'ExamplePassword123!',role:'admin'});
 assert.equal(first.status,201);assert.equal(first.data.role,'customer');
 const second=await call('/auth/register','POST',{name:'Customer Two',email:'two@example.com',password:'ExamplePassword123!'});
 assert.equal(second.status,201);
 const barberUser=await User.create({name:'John Doe',email:'john@example.com',role:'barber',passwordHash:'test-only'});
 const adminUser=await User.create({name:'Admin',email:'admin@example.com',role:'admin',passwordHash:'test-only'});
 const haircut=await Service.create({name:'Haircut',durationMinutes:30});
 const color=await Service.create({name:'Hair coloring',durationMinutes:90});
 const unsupported=await Service.create({name:'Hair art',durationMinutes:60});
 const barber=await Barber.create({user:barberUser._id,services:[haircut._id,color._id]});
 const barberCookie='session='+issueToken(barberUser,secret),adminCookie='session='+issueToken(adminUser,secret);
 const day=new Date(Date.now()+7*86400000);
 while(day.getUTCDay()===0) day.setUTCDate(day.getUTCDate()+1);
 const date=day.toISOString().slice(0,10),barberId=String(barber._id),serviceId=String(haircut._id);
 assert.equal((await call('/admin/services','GET',null,first.cookie)).status,403);
 assert.equal((await call('/barbers/'+barberId+'/availability?date='+date+'&service='+unsupported._id)).status,400);
 const payload={barber:barberId,service:serviceId,date,time:'09:00'};
 const contenders=await Promise.all([call('/appointments','POST',payload,first.cookie),call('/appointments','POST',payload,second.cookie)]);
 assert.deepEqual(contenders.map(r=>r.status).sort(),[201,409]);
 assert.equal(await Appointment.countDocuments({status:'confirmed'}),1);
 const winner=contenders.findIndex(r=>r.status===201),booked=contenders[winner].data;
 const winnerCookie=winner===0?first.cookie:second.cookie,loserCookie=winner===0?second.cookie:first.cookie;
 assert.equal((await call('/appointments/'+booked._id+'/status','PATCH',{status:'cancelled'},loserCookie)).status,403);
 assert.equal((await call('/barbers/'+barberId+'/schedule','PUT',{date,closed:false,workingHours:{start:'09:00',end:'18:00'},blocked:[{start:'09:00',end:'10:00'}]},barberCookie)).status,409);
 assert.equal((await call('/appointments/'+booked._id+'/reschedule','PATCH',{date,time:'12:00'},winnerCookie)).status,409);
 assert.equal((await Appointment.findById(booked._id)).startAt.toISOString(),date+'T01:00:00.000Z');
 const moved=await call('/appointments/'+booked._id+'/reschedule','PATCH',{date,time:'10:00'},winnerCookie);
 assert.equal(moved.status,200);
 assert.equal((await call('/appointments/'+booked._id+'/reschedule/'+moved.data.rescheduleRequest._id,'PATCH',{action:'approve'},barberCookie)).status,200);
 assert.equal((await call('/appointments','POST',{...payload,time:'09:00'},loserCookie)).status,201);
 assert.equal((await call('/appointments/'+booked._id+'/status','PATCH',{status:'cancelled'},winnerCookie)).status,200);
 const coloring=await call('/appointments','POST',{...payload,service:String(color._id),time:'10:00'},winnerCookie);
 assert.equal(coloring.status,201);
 const starts=await call('/barbers/'+barberId+'/availability?date='+date+'&service='+serviceId);
 assert.ok(!starts.data.times.includes('11:00'));assert.ok(starts.data.times.includes('11:30'));
 assert.equal((await call('/barbers/'+barberId+'/schedule','PUT',{date,closed:false,workingHours:{start:'09:00',end:'18:00'},blocked:[{start:'14:00',end:'15:00'}]},barberCookie)).status,200);
 assert.equal((await call('/appointments','POST',{...payload,time:'13:45'},first.cookie)).status,409);
 const service=await call('/admin/services','POST',{name:'Beard trim',durationMinutes:15},adminCookie);
 assert.equal(service.status,201);
 assert.equal((await call('/admin/services/'+service.data._id,'PUT',{name:'Beard trim',durationMinutes:30},adminCookie)).status,200);
 assert.equal((await call('/admin/services/'+service.data._id,'DELETE',null,adminCookie)).status,200);
 assert.equal((await call('/auth/logout','POST',{},first.cookie)).status,200);
 assert.equal((await call('/me','GET',null,first.cookie)).status,401);
});
